#!/usr/bin/env node
/* Rebuild data/board.js from a fresh rankings file.

     node scripts/import_rankings.mjs rankings.txt > data/board.new.js
     mv data/board.new.js data/board.js

   Same forgiving parser the in-app "Paste fresh rankings" button uses, so it
   eats numbered cheat sheets, FantasyPros CSV exports and Boris Chen tier
   blocks. Use this when you are on a laptop the day before the draft; use the
   in-app paste when you are on your phone.

   Bye weeks already known from the current board are carried over, so you only
   need name / position / rank in the new file.                              */

import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const file = process.argv[2];
if (!file) {
  console.error('usage: node scripts/import_rankings.mjs <rankings.txt> > data/board.js');
  process.exit(1);
}

/* Run the browser modules in a vm context where `window` IS the global, which
   is exactly how they see the world in a browser. */
const sandbox = {
  console,
  localStorage: { getItem: () => null, setItem() {}, removeItem() {} },
  setInterval() {}, clearTimeout() {}, setTimeout() {},
  document: {
    readyState: 'complete', addEventListener() {},
    getElementById: () => ({ addEventListener() {}, querySelectorAll: () => [], style: {},
      appendChild() {}, value: '', checked: false, innerHTML: '', textContent: '' }),
    createElement: () => ({ style: {}, appendChild() {}, addEventListener() {},
      classList: { add() {}, remove() {}, toggle() {} } }),
    querySelectorAll: () => []
  }
};
sandbox.window = sandbox;
sandbox.globalThis = sandbox;
vm.createContext(sandbox);
const load = (rel) => vm.runInContext(fs.readFileSync(path.join(ROOT, rel), 'utf8'), sandbox, { filename: rel });

load('data/board.js');
load('data/notes.js');
load('assets/util.js');
load('assets/engine.js');
load('assets/state.js');
sandbox.Sleeper = { Sync: {}, on() {}, start() {}, stop() {},
                    connect: () => Promise.resolve(), poll: () => Promise.resolve(),
                    playersLoadedAt: () => null, diagnose: () => Promise.resolve([]),
                    loadPlayers: () => Promise.resolve(0) };
sandbox.UI = { render() {}, setView() {}, Sheet: { open() {} }, setBoardFilter() {},
               setBoardQuery() {}, moreBoard() {}, getView: () => 'now',
               posChip: () => ({}), el: sandbox.U.el };
load('assets/main.js');
const win = sandbox;

const text = fs.readFileSync(file, 'utf8');
const parsed = win.Importers.parseRankings(text);
if (!parsed.count) {
  console.error('Parsed 0 players. Each line needs at least a name and a position.');
  process.exit(1);
}

const oldByes = win.BOARD_DATA.byes;
const oldByKey = {};
win.BOARD_DATA.players.forEach(p => { oldByKey[win.State.keyOf(p.name, p.pos)] = p; });

const rows = Object.entries(parsed.map)
  .map(([key, v]) => ({ key, ...v }))
  .sort((a, b) => a.rank - b.rank);

const byes = { ...oldByes };
rows.forEach(r => { if (r.team && r.bye != null && byes[r.team] == null) byes[r.team] = r.bye; });

const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
const lines = rows.map(r => {
  const prev = oldByKey[r.key];
  const team = r.team || (prev && prev.team) || null;
  const tier = r.tier != null ? r.tier : (prev && prev.tier != null ? prev.tier : null);
  return `    ["${esc(r.name)}", "${r.pos}", ${team ? `"${team}"` : 'null'}, ${tier == null ? 'null' : tier}]`;
});

process.stdout.write(`/* GENERATED by scripts/import_rankings.mjs on ${new Date().toISOString().slice(0, 10)}
   Source file: ${path.basename(file)}   (${rows.length} players)
   Regenerate any time before the draft; see README. */

window.BOARD_DATA = (function () {
  var BYES = ${JSON.stringify(byes, null, 4).replace(/\n/g, '\n  ')};

  // [name, pos, team, tier] — rank is array order.
  var ROWS = [
${lines.join(',\n')}
  ];

  var players = ROWS.map(function (r, i) {
    return {
      name: r[0], pos: r[1], team: r[2], tier: r[3],
      rank: i + 1,
      bye: r[2] && BYES[r[2]] != null ? BYES[r[2]] : null,
      adp: null,
      source: 'import'
    };
  });

  return {
    generated: '${new Date().toISOString().slice(0, 10)}',
    source: 'imported from ${esc(path.basename(file))}',
    byes: BYES,
    players: players
  };
})();
`);
console.error(`Wrote ${rows.length} players.${parsed.errors.length ? ` Skipped ${parsed.errors.length} unreadable line(s).` : ''}`);
